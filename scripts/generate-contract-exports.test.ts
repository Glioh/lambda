import assert from "node:assert/strict";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, it } from "node:test";
import { discoverContractModules, generateContractExports, renderContractExports, shouldRegenerateContractExports, } from "./generate-contract-exports.js";

async function withTempContracts(run: (root: string) => Promise<void>): Promise<void> {
	const root = await mkdtemp(join(tmpdir(), "lambda-contract-exports-"));
	try {
		await run(root);
	} finally {
		await rm(root, { recursive: true, force: true });
	}
}

describe("contract export generator", () => {
	it("discovers nested TypeScript modules and excludes generated, test, and irrelevant files", async () => {
		await withTempContracts(async root => {
			await mkdir(join(root, "nested", "__tests__"), { recursive: true });
			await writeFile(join(root, "index.ts"), "stale");
			await writeFile(join(root, "root.ts"), "");
			await writeFile(join(root, "nested", "child.ts"), "");
			await writeFile(join(root, "nested", "child.test.ts"), "");
			await writeFile(join(root, "nested", "child.spec.ts"), "");
			await writeFile(join(root, "nested", "types.d.ts"), "");
			await writeFile(join(root, "nested", "readme.js"), "");
			await writeFile(join(root, "nested", "__tests__", "ignored.ts"), "");

			assert.deepEqual(await discoverContractModules(root), ["nested/child.ts", "root.ts"]);
		});
	});

	it("sorts paths, emits export-star statements, and uses .js specifiers", () => {
		assert.equal(
			renderContractExports(["zeta.ts", "nested/alpha.ts"]),
			`/**
 * AUTO-GENERATED by scripts/generate-contract-exports.ts.
 *
 * Do not edit this file directly.
 * Add or remove modules under src/contracts instead.
 */

export * from "./nested/alpha.js";
export * from "./zeta.js";
`,
		);
	});

	it("does not rewrite unchanged output and ignores its own watch event", async () => {
		await withTempContracts(async root => {
			await writeFile(join(root, "contract.ts"), "");
			assert.equal(await generateContractExports(root), true);
			const generated = await readFile(join(root, "index.ts"), "utf8");
			assert.equal(await generateContractExports(root), false);
			assert.equal(await readFile(join(root, "index.ts"), "utf8"), generated);
			assert.equal(
				shouldRegenerateContractExports("change", "index.ts", root, join(root, "index.ts")),
				false,
			);
			assert.equal(
				shouldRegenerateContractExports("change", "contract.test.ts", root, join(root, "index.ts")),
				false,
			);
			assert.equal(
				shouldRegenerateContractExports("rename", "contract.txt", root, join(root, "index.ts")),
				true,
			);
		});
	});
});
