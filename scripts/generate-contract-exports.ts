/**
 * Discovers API contract modules and regenerates contracts/index.ts with deterministic re-exports. This
 * removes manual barrel maintenance and prevents new schemas from being omitted from API generation.
 */

import { watch } from "node:fs";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { basename, dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const contractsDirectory = resolve(
	dirname(fileURLToPath(import.meta.url)),
	"../apps/api/src/contracts",
);
const generatedHeader = `/**
 * AUTO-GENERATED by scripts/generate-contract-exports.ts.
 *
 * Do not edit this file directly.
 * Add or remove modules under src/contracts instead.
 */

`;

function isContractModule(filePath: string, root: string): boolean {
	const fileName = basename(filePath).toLowerCase();
	return (
		filePath !== join(root, "index.ts") &&
		fileName.endsWith(".ts") &&
		!fileName.endsWith(".d.ts") &&
		!fileName.endsWith(".test.ts") &&
		!fileName.endsWith(".spec.ts")
	);
}

export async function discoverContractModules(root: string): Promise<string[]> {
	const modules: string[] = [];

	async function visit(directory: string): Promise<void> {
		for (const entry of await readdir(directory, { withFileTypes: true })) {
			const filePath = join(directory, entry.name);
			if (entry.isDirectory()) {
				if (entry.name !== "__tests__") await visit(filePath);
				continue;
			}
			if (isContractModule(filePath, root)) {
				modules.push(relative(root, filePath).split(sep).join("/"));
			}
		}
	}

	await visit(root);
	return modules.sort();
}

export function renderContractExports(modules: readonly string[]): string {
	const exports = [...modules]
		.sort()
		.map(modulePath => `export * from "./${modulePath.replace(/\.ts$/i, ".js")}";`);
	return `${generatedHeader}${exports.join("\n")}${exports.length ? "\n" : ""}`;
}

export async function generateContractExports(
	root = contractsDirectory,
	output = join(root, "index.ts"),
): Promise<boolean> {
	const generated = renderContractExports(await discoverContractModules(root));
	let current = "";
	try {
		current = await readFile(output, "utf8");
	} catch (error) {
		if (!(error instanceof Error) || (error as NodeJS.ErrnoException).code !== "ENOENT") {
			throw error;
		}
	}

	if (current === generated) return false;
	await writeFile(output, generated, "utf8");
	return true;
}

export function shouldRegenerateContractExports(
	eventType: "rename" | "change",
	filename: string | Buffer | null,
	root: string,
	output: string,
): boolean {
	const relativePath = filename?.toString();
	if (relativePath && resolve(root, relativePath) === resolve(output)) return false;
	return (
		eventType === "rename" || !relativePath || isContractModule(join(root, relativePath), root)
	);
}

export async function watchContractExports(
	root = contractsDirectory,
	output = join(root, "index.ts"),
	initial = true,
): Promise<void> {
	if (initial) await generateContractExports(root, output);
	let timer: NodeJS.Timeout | undefined;
	const watcher = watch(root, { recursive: true }, (eventType, filename) => {
		if (!shouldRegenerateContractExports(eventType, filename, root, output)) return;
		if (timer) clearTimeout(timer);
		timer = setTimeout(() => {
			timer = undefined;
			void generateContractExports(root, output).catch(error => console.error(error));
		}, 100);
	});

	await new Promise<void>(resolvePromise => {
		const close = () => {
			if (timer) clearTimeout(timer);
			watcher.close();
			process.off("SIGINT", close);
			process.off("SIGTERM", close);
			resolvePromise();
		};
		process.once("SIGINT", close);
		process.once("SIGTERM", close);
	});
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
	const run = process.argv.includes("--watch")
		? () => watchContractExports(undefined, undefined, !process.argv.includes("--skip-initial"))
		: generateContractExports;
	void run().catch(error => {
		console.error(error);
		process.exitCode = 1;
	});
}
